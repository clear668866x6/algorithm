void solve() {
    double a, b, c;
    cin >> a >> b >> c;

    double p1 = a / 16.0, p2 = b / 16.0, p3 = c / 16.0;

    double ans = pow(p1, 12) * (pow(p2, 4) + pow(p3, 4));

    double t = (16 * 15 * 14 * 13.0) / (2.0 * 3.0 * 4.0);

    ans *= t;

    ans += pow(p1, 16);

    cout << fixed << setprecision(12) << ans << endl;
}

