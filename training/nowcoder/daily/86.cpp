void solve() {
    string s;
    cin >> s;

    int a = s[0] - '0', b = s[1] - '0', c = s[2] - '0';
    int d = (int)((a * 100 + b * 10 + c) / 10.0 + 0.5);

    int d1 = d / 10, d2 = d % 10;
    int cnt = sz(s) - 1;
    if (d1 >= 10) {
        cout << d1 / 10 << "." << d1 % 10 << "*10^" << (cnt + 1) << endl;
    } else {
        cout << d1 << "." << d2 << "*10^" << cnt << endl;
    }
}

