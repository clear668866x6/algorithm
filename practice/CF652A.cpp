void solve() {
    int h1, h2, a, b;
    cin >> h1 >> h2 >> a >> b;

    if (a > b) {
        int t = h1 + 8 * a;
        int ans = 0;
        while (t < h2) {
            t -= (12 * b);
            t += (12 * a);
            ans++;
        }
        cout << ans << endl;
    } else if (a <= b) {
        if (h1 + 8 * a >= h2) {
            cout << 0 << endl;
        } else {
            cout << -1 << endl;
        }
    }
}

